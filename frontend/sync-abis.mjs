#!/usr/bin/env node

import fs from 'fs'
import path from 'path'

const CONTRACTS_OUT = path.resolve('../contracts/out')
const FRONTEND_ABI = path.resolve('src/lib/abi.ts')

function extractAbi(contractName) {
  const jsonPath = path.join(CONTRACTS_OUT, `${contractName}.sol`, `${contractName}.json`)
  if (!fs.existsSync(jsonPath)) {
    console.error(`Not found: ${jsonPath}`)
    return null
  }
  const content = JSON.parse(fs.readFileSync(jsonPath, 'utf8'))
  return content.abi
}

function generateAbiFile() {
  const orderBookAbi = extractAbi('OrderBook')
  const mockErc20Abi = extractAbi('MockERC20')

  if (!orderBookAbi || !mockErc20Abi) {
    console.error('Failed to extract ABIs')
    process.exit(1)
  }

  const content = `// Auto-generated by sync-abis.mjs - DO NOT EDIT MANUALLY
// Run: npm run abi (from frontend directory)

import type { Abi } from 'viem'

export const ORDER_BOOK_ABI = ${JSON.stringify(orderBookAbi, null, 2)} as const

export const ERC20_ABI = ${JSON.stringify(mockErc20Abi, null, 2)} as const
`

  fs.writeFileSync(FRONTEND_ABI, content)
  console.log('✓ ABIs synced to', FRONTEND_ABI)
  console.log(`  OrderBook: ${orderBookAbi.length} items`)
  console.log(`  MockERC20: ${mockErc20Abi.length} items`)
}

generateAbiFile()